import { readFile, writeFile } from "node:fs/promises";
const parts = [];
for (const name of ["intersaison_plan_cycle.sql", "intersaison_plan_dynamic_guilds.sql"]) {
  const source = await readFile(new URL(name, import.meta.url), "utf8");
  if ((source.match(/^begin;$/gm) || []).length !== 1 || (source.match(/^commit;$/gm) || []).length !== 1) {
    throw new Error(`Unexpected transaction structure in ${name}`);
  }
  parts.push(`-- Source: ${name}\n${source.replace(/^begin;\r?\n/m, "").replace(/^commit;\r?\n?/m, "").trim()}`);
}
const output = new URL("intersaison_plan_cycle_install.sql", import.meta.url);
await writeFile(output, `-- GENERATED by prepare-intersaison-plan-migration.mjs. One atomic installation.\n-- No roster transfer, survey launch/closure or Discord delivery is performed.\nbegin;\n\n${parts.join("\n\n")}\n\ncommit;\n`, "utf8");
console.log("Generated scripts/intersaison_plan_cycle_install.sql");

const base = await readFile(new URL("intersaison_plan_cycle.sql", import.meta.url), "utf8");
const replacements = ["read_intersaison_plan", "save_intersaison_plan", "intersaison_plan_targets"].map((name) => {
  const match = base.match(new RegExp(`create or replace function public\\.${name}\\([\\s\\S]*?^(?:end )?\\$\\$;`, "m"));
  if (!match || /\ncreate or replace function/.test(match[0])) throw new Error(`Cannot isolate ${name}`);
  return match[0];
});
const tables = ["portal_organizations", "portal_guilds", "guild_members", "intersaison_assignments",
  "intersaison_plan_cycles", "intersaison_plan_events", "intersaison_plan_applications", "intersaison_plan_objective_bank",
  "intersaison_survey_seasons", "intersaison_survey_campaigns", "intersaison_survey_recipients", "intersaison_survey_responses",
  "intersaison_survey_placements", "intersaison_survey_forecast_roles", "intersaison_survey_objective_versions", "intersaison_survey_objective_items",
  "guild_dm_campaigns", "guild_dm_recipients"];
const inventory = tables.map(name => `'${name}'`).join(",");
await writeFile(new URL("intersaison_plan_removals.sql", import.meta.url), `-- GENERATED by prepare-intersaison-plan-migration.mjs.
-- Supplemental installation only: no transfer, survey change, campaign or message.
-- Existing plan edits remain supported; all business rows are asserted unchanged.
begin isolation level repeatable read;
do $$ begin
  if to_regprocedure('public.save_intersaison_plan(uuid,uuid,uuid,integer,text,jsonb)') is null then
    raise exception 'Installer intersaison_plan_cycle avant ce complément.';
  end if;
end $$;
create temporary table plan_removal_integrity(table_name text primary key, fingerprint text) on commit drop;
do $$ declare name text; signature text; begin
  foreach name in array array[${inventory}] loop
    execute format('select md5(coalesce(string_agg(to_jsonb(t)::text,chr(10) order by to_jsonb(t)::text),'''')) from public.%I t',name) into signature;
    insert into plan_removal_integrity values(name,signature);
  end loop;
end $$;

${replacements.join("\n\n")}

do $$ declare saved record; signature text; begin
  for saved in select * from plan_removal_integrity loop
    execute format('select md5(coalesce(string_agg(to_jsonb(t)::text,chr(10) order by to_jsonb(t)::text),'''')) from public.%I t',saved.table_name) into signature;
    if signature is distinct from saved.fingerprint then raise exception 'Données modifiées dans % : installation annulée.',saved.table_name; end if;
  end loop;
end $$;
commit;
`, "utf8");
console.log("Generated scripts/intersaison_plan_removals.sql (three function replacements; unchanged business rows)");
