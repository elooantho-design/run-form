import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { startGuildSurveyPreview } from "./guild-survey-preview.mjs";

if (!process.env.PLAYWRIGHT_MODULE_PATH) throw Error("PLAYWRIGHT_MODULE_PATH required for isolated UI tests.");
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH).href);
const output = resolve(process.env.SURVEY_TEST_OUTPUT || ".guild-survey-browser-test");
await mkdir(output, { recursive: true });
const server = await startGuildSurveyPreview(5193);
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || "msedge" });
const base = "http://127.0.0.1:5193/__guild-surveys-preview";
const reports = [];
try {
  for (const width of [1440, 768, 390, 320]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } });
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
    await page.goto(base);
    await page.getByRole("button", { name: /Projet de/ }).click();
    await page.getByRole("button", { name: "Relancer les sans reponse" }).click();
    await page.getByLabel("Filtrer par guilde").first().selectOption("G8");
    await page.getByText("4 MP eligibles", { exact: true }).waitFor();
    const mutationsBefore = await page.evaluate(() => window.surveyCalls.filter(c => ["save", "publish", "remind", "close", "answer"].includes(c.action)).length);
    assert.equal(mutationsBefore, 0, "Opening the list, details and preview cannot create any delivery");
    const confirmation = page.getByRole("button", { name: "Confirmer l'envoi de 4 MP" });
    assert.equal(await confirmation.isDisabled(), true);
    await page.getByRole("checkbox", { name: /Je confirme l'envoi global/ }).check();
    await page.getByRole("dialog").evaluate(el => { el.scrollTop = 0; });
    await page.screenshot({ path: resolve(output, `reminder-preview-${width}.png`), fullPage: true });
    const overflow = await page.evaluate(() => [...document.querySelectorAll('[role="dialog"]')].some(el => el.scrollWidth > el.clientWidth + 1));
    assert.equal(overflow, false, "No modal horizontal overflow");
    await confirmation.dblclick();
    await page.getByText("4 invitations ajoutees a la file progressive.", { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => window.surveyCalls.filter(c => c.action === "remind").length), 1);
    const sent = await page.evaluate(() => window.surveyCalls.find(c => c.action === "remind"));
    assert.equal("guildCode" in sent.args.payload, false, "The visual filter cannot narrow the confirmed global operation");
    const download = page.waitForEvent("download"); await page.getByRole("button", { name: "CSV", exact: true }).click();
    assert.match((await download).suggestedFilename(), /^sondage-.*\.csv$/);
    assert.deepEqual(errors, []);
    await page.close(); reports.push({ width, reminderPreviewReadOnly: true, globalFilterIndependent: true, doubleClickProtected: true, csv: true, noOverflow: true });
  }
  const editor = await browser.newPage({ viewport: { width: 390, height: 950 } });
  await editor.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
  await editor.goto(base + "?create=1");
  await editor.getByLabel("Modele de sondage").selectOption("reorganization");
  assert.match(await editor.getByLabel("Titre du sondage").inputValue(), /DEUS/);
  await editor.getByRole("button", { name: "Ajouter une question", exact: true }).click();
  await editor.getByLabel("Intitule question 4").fill("Une question supplementaire");
  await editor.getByLabel("Type question 4").selectOption("multiple");
  await editor.getByLabel("Question 4, proposition 1", { exact: true }).fill("Choix A");
  await editor.getByLabel("Question 4, proposition 2", { exact: true }).fill("Choix B");
  await editor.getByLabel("Monter la question 4", { exact: true }).click();
  assert.equal(await editor.getByLabel("Intitule question 3").inputValue(), "Une question supplementaire");
  await editor.getByLabel("Supprimer la question 4", { exact: true }).click();
  assert.equal(await editor.locator('input[aria-label^="Intitule question"]').count(), 3);
  await editor.getByRole("button", { name: "Enregistrer le brouillon", exact: true }).click();
  await editor.getByText("Brouillon enregistre. Aucun MP envoye.").waitFor();
  assert.equal(await editor.evaluate(() => window.surveyCalls.filter(c => c.action === "publish").length), 0);
  await editor.getByRole("button", { name: "Previsualiser la publication" }).click();
  await editor.getByRole("checkbox", { name: /Je confirme l'envoi global/ }).check();
  await editor.getByRole("button", { name: "Confirmer l'envoi de 5 MP" }).click();
  await editor.getByText("5 invitations ajoutees a la file progressive.").waitFor();
  assert.equal(await editor.evaluate(() => window.surveyCalls.filter(c => c.action === "publish").length), 1);
  await editor.close();
  for (const width of [1440, 390, 320]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } });
    await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
    await page.goto(base + "?mode=member"); await page.getByRole("button", { name: /Mes sondages/ }).click();
    await page.getByRole("button", { name: /Projet de/ }).click();
    await page.getByRole("radio").first().check(); await page.getByRole("checkbox").first().check();
    await page.getByRole("textbox").fill("Avis personnel fictif");
    await page.getByRole("dialog").evaluate(el => { el.scrollTop = 0; });
    await page.screenshot({ path: resolve(output, `member-answer-${width}.png`), fullPage: true });
    assert.equal(await page.evaluate(() => [...document.querySelectorAll('[role="dialog"]')].some(el => el.scrollWidth > el.clientWidth + 1)), false);
    await page.getByRole("button", { name: "Enregistrer ma reponse" }).dblclick();
    await page.getByText("Votre reponse a ete enregistree.").waitFor();
    assert.equal(await page.evaluate(() => window.surveyCalls.filter(c => c.action === "answer").length), 1);
    await page.getByRole("textbox").fill("Avis modifie"); await page.getByRole("button", { name: "Modifier ma reponse" }).click();
    await page.waitForFunction(() => window.surveyCalls.filter(c => c.action === "answer").length === 2);
    assert.equal(await page.evaluate(() => window.surveyCalls.filter(c => c.action === "answer")[1].args.expectedRevision), 1);
    await page.close(); reports.push({ width, memberAnswer: true, editableOwnAnswer: true, noOverflow: true });
  }
  const conflict = await browser.newPage();
  await conflict.goto(base);
  await conflict.getByRole("button", { name: /Projet de/ }).click();
  await conflict.getByRole("button", { name: "Relancer les sans reponse" }).click();
  await conflict.getByRole("checkbox", { name: /Je confirme l'envoi global/ }).check();
  await conflict.evaluate(() => { window.surveyConflict = true; });
  await conflict.getByRole("button", { name: "Confirmer l'envoi de 4 MP" }).click();
  await conflict.getByRole("alert").filter({ hasText: /destinataires ont change/ }).waitFor();
  assert.equal(await conflict.getByRole("button", { name: "Confirmer l'envoi de 4 MP" }).count(), 0);
  assert.equal(await conflict.evaluate(() => window.surveyCalls.filter(c => c.action === "remind").length), 1);
  await conflict.close();
  const closed = await browser.newPage();
  await closed.goto(base + "?mode=member&closed=1");
  await closed.getByRole("button", { name: /Mes sondages/ }).click();
  await closed.getByRole("button", { name: /Projet de/ }).click();
  await closed.getByText("Ce sondage est cloture.").waitFor();
  assert.equal(await closed.getByRole("textbox").isDisabled(), true);
  assert.equal(await closed.getByRole("button", { name: "Enregistrer ma reponse" }).count(), 0);
  await closed.close();
  const optional = await browser.newPage();
  await optional.goto(base + "?mode=member&optional=1");
  await optional.getByRole("button", { name: /Mes sondages/ }).click();
  await optional.getByRole("button", { name: /Projet de/ }).click();
  const choice = optional.getByRole("radio").first();
  await choice.check();
  await optional.getByRole("button", { name: /Effacer le choix/ }).click();
  assert.equal(await choice.isChecked(), false, "An optional single choice can be cleared");
  await optional.close();
  reports.push({ stalePreviewRequiresNewConfirmation: true, closedResponseReadOnly: true, optionalSingleChoiceClearable: true });
  await writeFile(resolve(output, "browser-results.json"), JSON.stringify(reports, null, 2));
  console.log("Guild-survey browser checks passed: editor, publication and reminders simulated, CSV, own answers, desktop/mobile.");
} finally { await browser.close(); await server.close(); }
