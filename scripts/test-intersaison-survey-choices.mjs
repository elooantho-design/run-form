const recipientId="10000000-0000-4000-8000-000000000001", user="111111111111111111";
const customId=`interchoice:${recipientId}:${user}`;
const full=Object.fromEntries(Array.from({length:7},(_,i)=>[`G${i+1}`,"x".repeat(600)]));
const preview=buildSurveyTwoDiscordPayload(full);
const sent=buildSurveyTwoDiscordPayload(full,{recipientId,discordUserId:user});
assert.deepEqual(sent.embeds,preview.embeds,"the sent objectives and preview are exactly the same");
assert.deepEqual(sent.content,preview.content);
assert.equal(sent.components[0].components[0].custom_id,customId);
assert.equal(sent.components[0].components[0].disabled,false);
assert.ok(sent.components[0].components[0].custom_id.length<=100);
assert.deepEqual(sent.allowedMentions,{parse:[]});
assert.throws(()=>buildSurveyChoiceModal(customId,"222222222222222222"),/destinataire/);
const modal=buildSurveyChoiceModal(customId,user);
assert.equal(modal.type,9);
assert.equal(modal.data.components[0].component.options.length,7);
assert.equal(modal.data.components[1].component.options.length,8);
assert.equal(modal.data.components[0].component.required,true);
assert.equal(modal.data.components[1].component.required,false);
assert.equal(modal.data.components[2].component.required,false);
assert.deepEqual(validateSurveyChoice("G1","none",""),{firstChoice:"G1",secondChoice:"",comment:""});
assert.throws(()=>validateSurveyChoice("","G1",""),/premier/);
assert.throws(()=>validateSurveyChoice("G1","G1",""),/différent/);
assert.throws(()=>validateSurveyChoice("MAD G1","",""),/premier/);
assert.throws(()=>validateSurveyChoice("G1","G8",""),/cluster/);
assert.throws(()=>validateSurveyChoice("G1","","x".repeat(1901)),/1900/);
const components=[{type:18,component:{custom_id:"first_choice",values:["G2"]}},{type:18,component:{custom_id:"second_choice",values:[]}},{type:18,component:{custom_id:"comment_text",value:"  Texte intégral\n  "}}];
assert.equal(readSurveyChoiceFields(components).comment,"  Texte intégral\n  ");
assert.equal(readSurveyChoiceFields([{component:{customId:"first_choice",values:["G3"]}}]).firstChoice,"G3","Discord.js normalized components are supported");
assert.throws(()=>readSurveyChoiceFields([{component:{custom_id:"first_choice",values:["G1","G2"]}}]),/seul choix/);
assert.throws(()=>readSurveyChoiceFields([...components,...components]),/dupliqué/);
