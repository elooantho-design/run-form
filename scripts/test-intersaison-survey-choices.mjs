await saveSurveyChoiceResponse(fake,{customId:modal.data.custom_id,userId:user,interactionId:"123456789012345678",components});
assert.equal(rpcCalls,1);
await assert.rejects(saveSurveyChoiceResponse(fake,{customId:modal.data.custom_id,userId:"222222222222222222",components}),/destinataire/);
assert.equal(rpcCalls,1);
await assert.rejects(saveSurveyChoiceResponse({rpc:async()=>({error:{message:"Sauvegarde indisponible"}})},{customId:modal.data.custom_id,userId:user,components}),/Sauvegarde indisponible/);
const noNetwork=new Proxy({}, {get(){throw new Error("Network before modal is forbidden");}});
assert.equal((await handleDiscordReproComponentInteraction(noNetwork,{data:{custom_id:customId},user:{id:user}})).type,9,"opening the choice modal never fetches Supabase or Discord");

const members=Array.from({length:31},(_,i)=>({id:`m${i}`,watcher_name:`Joueur ${i}`,guild_code:"G3"}));
const recipients=members.map((m,i)=>({id:`r${i}`,member_id:m.id,member_key:m.id,member_name_snapshot:m.watcher_name,guild_code_snapshot:"G3"}));
const responses=members.map((m,i)=>({id:`a${i}`,survey_recipient_id:`r${i}`,first_choice_guild_code:"G1",second_choice_guild_code:"G2",poll_number:2,is_current:true,responded_at:"2026-10-18T10:00:00Z"}));
let plan=buildSurveyChoiceForecast({members,recipients,responses});
assert.equal(plan.guilds[0].count,31); assert.equal(plan.guilds[0].overCapacity,true); assert.equal(plan.guilds[1].count,0,"second choices do not count twice");
assert.equal(plan.unassigned.length,0);
assert.equal(getSurveyMemberDeliveryStatus({surveyRecipient:recipients[0],response:responses[0]}).color,"green","first choice alone is a valid response");
plan=buildSurveyChoiceForecast({members,recipients,responses,placements:[{member_key:"m0",member_id:"m0",revision:1,action:"set",guild_code:"G2"}]});
assert.equal(plan.guilds[0].count,30); assert.equal(plan.guilds[1].count,1);
assert.equal(plan.players.find(p=>p.memberKey==="m0").hasDifference,true);
assert.equal(plan.players.length,31);
