import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { buildSurveyChoiceForecast, buildSurveyChoiceModal, readSurveyChoiceFields, saveSurveyChoiceResponse, validateSurveyChoice } from "../src/lib/intersaisonSurveyChoices.js";
